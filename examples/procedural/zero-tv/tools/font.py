# A 5x7 pixel font with 2 rows of descenders, for the labels of the tapes.
# Each glyph is 9 rows of 5 pixels. Rows 0-6 sit on the baseline, rows 7-8
# are descenders. Usage: font.py OUT_ATLAS.png
import sys

