# Small vowels with tonos: the plain letter with an accent above it.
for accented, plain in zip("άέήίόύώ", "αεηιουω"):
    rows = list(G[plain])
    rows[0] = "...#."
    rows[1] = "..#.." if rows[1] == E else rows[1]
    G[accented] = rows

# The order of the atlas. The shader maps each code point to its index.
ORDER = [chr(c) for c in range(32, 127)]
ORDER += [chr(c) for c in range(0x391, 0x3AA)]   # Α..Ω (U+03A2 is not used)
ORDER += [chr(c) for c in range(0x3B1, 0x3CA)]   # α..ω
ORDER += list("άέήί") + list("όύώ")
CELL_W, CELL_H, COLS = 6, 10, 16

def atlas():
    from PIL import Image
    rows = (len(ORDER) + COLS - 1) // COLS
    img = Image.new("RGBA", (COLS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
    for i, ch in enumerate(ORDER):
        g = G.get(ch, G["?"])
        ox, oy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        for y, row in enumerate(g):
            for x, bit in enumerate(row):
                if bit == "#":
                    img.putpixel((ox + x, oy + y), (255, 255, 255, 255))
    return img

if __name__ == "__main__":
    missing = [c for c in ORDER if c not in G and c != "΢"]
    assert not missing, missing
    img = atlas()
    img.save(sys.argv[1], optimize=True)
    print("glyphs", len(ORDER), "atlas", img.size)
